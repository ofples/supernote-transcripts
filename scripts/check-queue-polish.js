(async () => {
  const c = window.__transcriptUIFixture;
  const root = () => document.querySelector('.st-fullscreen-modal');
  const assert = (ok, message) => { if (!ok) throw Error(message); };
  root().querySelector('[aria-label="Back"]').click();
  const cue = root().querySelector('.st-queue-link');
  const label = cue.querySelector('.st-queue-hint').getBoundingClientRect();
  const arrow = cue.querySelector('.st-queue-arrow').getBoundingClientRect();
  assert(Math.abs((label.top + label.bottom) / 2 - (arrow.top + arrow.bottom) / 2) < 2, 'Queue arrow misaligned');
  const rule = c.config.rules[0];
  const second = rule.source + '/Second.note';
  const duplicate = rule.source + '/Sub/Second.note';
  c.store.notebooks[duplicate] = {...c.store.notebooks[second], source: duplicate};
  c.store.queue.push({source: duplicate, force: false});
  await c.saveConfig();
  root().querySelector('[aria-label="Open queue"]').click();
  const duplicates = [...root().querySelectorAll('.st-queue-copy')].filter(x => x.querySelector('strong').textContent === 'Second');
  assert(duplicates.length === 2 && duplicates.every(x => x.querySelector('.st-source-heading .st-source-parent')), 'Duplicate paths missing');
  root().querySelector('[aria-label="Back"]').click();
  rule.exclude.push('Second.note');
  await c.saveConfig();
  const toggle = root().querySelector('[aria-label="Expand Fixture"]');
  if (toggle) toggle.click();
  assert(!root().querySelector(`[data-notebook-id="${CSS.escape(second)}"]`), 'Excluded notebook remains in Sources');
  assert(c.store.notebooks[second], 'Exclusion removed cached notebook');
  root().querySelector('[aria-label="Open queue"]').click();
  assert(!root().querySelector(`[data-queue-key="next:${CSS.escape(second)}"]`), 'Excluded notebook remains queued');
  return {sharedQueueBars: true,iconControls: true, cueAligned: true, duplicatePathsInline: true, immediateExclusion: true, cachedStateKept: true, aiCalls: 0};
})();
